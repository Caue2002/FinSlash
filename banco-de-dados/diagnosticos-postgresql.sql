-- Estrutura e primeiros diagnósticos AWS com referências oficiais revisadas.
BEGIN;

CREATE TABLE IF NOT EXISTS aws_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cost_scenarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES aws_services(id) ON DELETE CASCADE,
    slug TEXT NOT NULL,
    title TEXT NOT NULL,
    summary TEXT NOT NULL,
    is_published BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (service_id, slug)
);

CREATE TABLE IF NOT EXISTS scenario_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id BIGINT NOT NULL REFERENCES cost_scenarios(id) ON DELETE CASCADE,
    step_type TEXT NOT NULL CHECK (step_type IN ('check', 'action', 'caution')),
    position SMALLINT NOT NULL CHECK (position > 0),
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    UNIQUE (scenario_id, step_type, position)
);

CREATE TABLE IF NOT EXISTS scenario_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id BIGINT NOT NULL REFERENCES cost_scenarios(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    url TEXT NOT NULL CHECK (
        url LIKE 'https://docs.aws.amazon.com/%'
        OR url LIKE 'https://aws.amazon.com/%'
    ),
    reviewed_at DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (scenario_id, url)
);

CREATE TABLE IF NOT EXISTS feedback_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL CHECK (category IN ('suggestion', 'issue', 'content')),
    message TEXT NOT NULL CHECK (char_length(btrim(message)) BETWEEN 10 AND 1000),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Guarda um HMAC por janela horária, nunca o endereço IP em texto claro.
CREATE TABLE IF NOT EXISTS feedback_rate_limits (
    address_hash CHAR(64) NOT NULL,
    window_start TIMESTAMPTZ NOT NULL,
    request_count INTEGER NOT NULL CHECK (request_count > 0),
    expires_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (address_hash, window_start)
);

CREATE INDEX IF NOT EXISTS cost_scenarios_published_idx
    ON cost_scenarios (service_id, slug)
    WHERE is_published = TRUE;
CREATE INDEX IF NOT EXISTS scenario_steps_order_idx
    ON scenario_steps (scenario_id, step_type, position);
CREATE INDEX IF NOT EXISTS scenario_sources_order_idx
    ON scenario_sources (scenario_id, title);
CREATE INDEX IF NOT EXISTS feedback_rate_limits_expiry_idx
    ON feedback_rate_limits (expires_at);

